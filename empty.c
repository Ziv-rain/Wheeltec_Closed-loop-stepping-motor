/**
 * ============================================================================
 * 轮趣 MS42CG + D36A 闭环步进电机 — 天猛星 MSPM0G3507
 * ============================================================================
 *
 * 接线指南 (引脚 100% 兼容天猛星, 无需修改):
 *
 *   [天猛星]                          [D36A 驱动器]
 *   PA24 (A0_3)  ──────────────────→  ST1   (STEP 脉冲)
 *   PA13         ──────────────────→  DIR1  (方向)
 *   PA12         ──────────────────→  EN1   (使能, 高电平锁轴)
 *   GND          ──────────────────→  GND   (⚠️ 必须共地)
 *
 *   [天猛星]                          [MS42CG 编码器]  6芯排线顺序:
 *   3.3V         ──────────────────→  VCC   (① ⚠️ 必须3.3V, 接5V烧MCU!)
 *   PA1          ──────────────────→  A     (② 编码器A相)
 *   PA0          ──────────────────→  B     (③ 编码器B相)
 *   PB20 (A0_6)  ──────────────────→  PWM   (④ 绝对角度)
 *   PA25 (A0_2)  ──────────────────→  Z     (⑤ 索引信号)
 *   GND          ──────────────────→  GND   (⑥)
 *
 *   [D36A]                           [MS42CG 电机]
 *   A+/A-  ────────────────────────→  电机 A+ A-
 *   B+/B-  ────────────────────────→  电机 B+ B-
 *
 *   供电:
 *   12V DC + → D36A VIN    12V DC - → D36A GND
 *   天猛星 USB-C 供电 (或 5V)
 *
 *   D36A 拨码开关 (默认): MS1/2/3=OFF(16细分), CUR1/2/3=OFF(1.44A)
 *   代码 D36A_MICROSTEP=16 必须与拨码一致!
 *
 *   串口: PA28(TX)/PA31(RX) → USB-TTL → PC, 115200-8-N-1
 *   (⚠️ 需外接 USB-TTL 模块, 天猛星板载 CH340E 走的是 PA10/PA11 不能用)
 *   上电后发送 A1 90 → 电机转 90°
 *
 * ⚠️ 注意事项:
 *   1. 编码器 VCC 必须 3.3V, 5V 会烧 MCU
 *   2. 严禁带电插拔电机功率线 (A+/A-/B+/B-)
 *   3. 12V 电源不要接反
 *   4. 首次上电用小角度测试: A1 5
 *
 * ============================================================================
 * 实验模式 (demo_config.h DEMO_SELECT):
 *   1 = 开环转动   2 = 编码器读取
 *   3 = 闭环自动   4 = 串口指令控制(默认)
 * ============================================================================
 */

#include "board.h"
#include "app_demo.h"
#include "encoder.h"
#include "motor.h"

int main(void)
{
    SYSCFG_DL_init();
    Board_LED_Init();
    Motor_Init();
    Encoder_Init();
    Demo_Init();

    NVIC_ClearPendingIRQ(TIMER_0_INST_INT_IRQN);
    NVIC_EnableIRQ(TIMER_0_INST_INT_IRQN);

    while (1) Demo_Process();
}

/**
 * TIMG0 5ms 周期中断
 * 编码器采样 + 闭环控制计算（实验 3/4 模式）
 */
void TIMER_0_INST_IRQHandler(void)
{
    if (DL_TimerG_getPendingInterrupt(TIMER_0_INST) == DL_TIMER_IIDX_ZERO) {
        Demo_Tick5ms();
    }
}
